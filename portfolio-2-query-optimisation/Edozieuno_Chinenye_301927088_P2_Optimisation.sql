CREATE SCHEMA IF NOT EXISTS p2_benchmark;

-- Create synthetic history table for benchmarking without altering Portfolio 1 tables
CREATE TABLE p2_benchmark.distributor_order_history (
    history_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL,
    distributor_id INT NOT NULL,
    order_date DATE NOT NULL,
    delivery_date DATE NOT NULL
);

-- Generate 100,000 plausible rows using existing distributor IDs (101, 102, 103)
INSERT INTO p2_benchmark.distributor_order_history (order_id, distributor_id, order_date, delivery_date)
SELECT 
    1000 + (i % 5000),
    101 + (i % 3),
    DATE '2025-01-01' + (i % 365),
    DATE '2025-01-01' + (i % 365) + (i % 4)
FROM generate_series(1, 100000) AS s(i);

-- Update statistics for the PostgreSQL query planner
