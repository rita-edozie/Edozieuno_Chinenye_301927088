BEGIN;

-- Category table
CREATE TABLE category (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR NOT NULL UNIQUE
);

-- Product table
-- Note (Rule 6): Foreign key RESTRICT prevents deletion if referenced; checking "active" order status requires a trigger or application logic.
CREATE TABLE product (
    product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR NOT NULL,
    category_id INT NOT NULL REFERENCES category(category_id) ON DELETE RESTRICT
);

-- Distributor table
CREATE TABLE distributor (
    distributor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_name VARCHAR NOT NULL,
    status VARCHAR NOT NULL CHECK (status IN ('Active', 'Inactive'))
);

-- Distributor order table
-- Note (Rule 2): Ensuring at least one order item cannot be enforced by a table constraint alone; requires a trigger or application logic.
CREATE TABLE distributor_order (
    order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id INT NOT NULL REFERENCES distributor(distributor_id) ON DELETE RESTRICT,
    order_date DATE NOT NULL,
    delivery_date DATE NOT NULL,
    CONSTRAINT chk_delivery_date CHECK (delivery_date >= order_date)
);

-- Order item table
-- Note (Rule 3): Stock limit validation against warehouse levels requires a trigger or application logic.
CREATE TABLE order_item (
    order_id INT NOT NULL REFERENCES distributor_order(order_id) ON DELETE CASCADE,
    product_id INT NOT NULL REFERENCES product(product_id) ON DELETE RESTRICT,
    quantity INT NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (order_id, product_id)
);

-- Warehouse stock table
-- Note (Rule 5): Future expiry dates enforced via CHECK constraint (expiry_date > receipt_date).
CREATE TABLE warehouse_stock (
    warehouse_id INT NOT NULL,
    product_id INT NOT NULL REFERENCES product(product_id) ON DELETE RESTRICT,
    stock_quantity INT NOT NULL CHECK (stock_quantity > 0),
    receipt_date DATE NOT NULL,
    expiry_date DATE NOT NULL,
    PRIMARY KEY (warehouse_id, product_id),
    CONSTRAINT chk_expiry_date CHECK (expiry_date > receipt_date)
);

COMMIT;